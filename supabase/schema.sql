create table if not exists public.prayer_schedule (
  id bigint generated by default as identity primary key,
  prayer_date date not null,
  name text not null,
  time time not null,
  display_order int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category text,
  event_date date not null,
  start_time text,
  created_at timestamptz not null default now()
);

create table if not exists public.donation_accounts (
  id bigint generated by default as identity primary key,
  bank_name text not null,
  account_number text not null,
  account_name text not null,
  is_active boolean not null default true,
  display_order int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  created_at timestamptz not null default now()
);

-- Data semua layanan masuk ke satu tabel.
-- form_data memakai JSONB supaya tiap layanan bisa mempunyai
-- field yang berbeda tanpa perlu membuat banyak tabel.
create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  service_type text not null,
  action_type text not null,
  service_name text not null,
  form_data jsonb not null default '{}'::jsonb,
  status text not null default 'baru',
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

