-- =========================================================
-- ADMIN AUTHORIZATION
-- 1) Buat user admin di Supabase Dashboard:
--    Authentication > Users > Add user
-- 2) Salin UUID user tersebut.
-- 3) Masukkan UUID ke public.admin_users.
-- =========================================================

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin',
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

-- Hapus policy lama bila script dijalankan ulang.
drop policy if exists "admins can read own admin record" on public.admin_users;
create policy "admins can read own admin record"
on public.admin_users for select to authenticated
using (user_id = (select auth.uid()));

-- Fungsi ini hanya mengembalikan true/false; data admin_users tidak dibuka ke anon.
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

